function setLanguage(lang) {
  currentLanguage = lang === "en" ? "en" : "ko";
  const dictionary = copy[currentLanguage];
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });
  root.lang = currentLanguage;
  toggleLabel.textContent = currentLanguage === "en" ? "KR" : "EN";
  toggle.setAttribute("aria-label", currentLanguage === "en" ? "한국어로 전환" : "Switch to English");
  localStorage.setItem("goyo-language", currentLanguage);
  applyConfigLabels();
  renderGallery();
}

function updateHeader() {
  header.dataset.elevated = window.scrollY > 20 ? "true" : "false";
}

function setActiveVertical(target) {
  if (!["h2h", "h2m"].includes(target)) {
    target = "h2h";
  }
  document.querySelectorAll("[data-vertical-tab]").forEach((tab) => {
    const isActive = tab.dataset.verticalTab === target;
    tab.classList.toggle("is-active", isActive);
    tab.setAttribute("aria-selected", String(isActive));
  });
  document.querySelectorAll("[data-vertical-panel]").forEach((panel) => {
    const isActive = panel.dataset.verticalPanel === target;
    panel.classList.toggle("is-active", isActive);
    panel.hidden = !isActive;
  });
}

function getVerticalHash() {
  const target = location.hash.replace("#", "").toLowerCase();
  return ["h2h", "h2m"].includes(target) ? target : "";
}

function scrollToVerticals() {
  const section = document.querySelector("#verticals");
  if (section) {
    section.scrollIntoView({ block: "start", behavior: "auto" });
  }
}

function applyConfigMedia() {
  const heroImage = document.querySelector("[data-config='heroImage']");
  if (heroImage && siteConfig.heroImage) {
    heroImage.src = siteConfig.heroImage;
  }

  const video = document.querySelector("[data-config='promoVideo']");
  if (video) {
    const source = video.querySelector("source");
    if (siteConfig.promoPoster) {
      video.poster = siteConfig.promoPoster;
    }
    if (source && siteConfig.promoVideo) {
      source.src = siteConfig.promoVideo;
      video.load();
    }
  }

  document.querySelectorAll("[data-audio-key]").forEach((audio) => {
    const key = audio.dataset.audioKey;
    const config = siteConfig.audio && siteConfig.audio[key];
    if (config && config.src) {
      audio.src = config.src;
    }
  });
}

function applyConfigLabels() {
  document.querySelectorAll("[data-audio-label]").forEach((label) => {
    const key = label.dataset.audioLabel;
    const config = siteConfig.audio && siteConfig.audio[key];
    if (!config) {
      return;
    }
    const nextLabel = currentLanguage === "en" ? config.labelEn : config.labelKo;
    if (nextLabel) {
      label.textContent = nextLabel;
    }
  });
}

function renderGallery() {
  const section = document.querySelector("[data-gallery-section]");
  const gallery = document.querySelector("[data-gallery]");
  if (!section || !gallery) {
    return;
  }

  const approved = (siteConfig.cesGallery || []).filter((item) => item && item.display !== false && item.src);
  section.hidden = approved.length === 0;
  gallery.innerHTML = "";

  approved.forEach((item) => {
    const figure = document.createElement("figure");
    figure.className = "gallery-card";

    const img = document.createElement("img");
    img.src = item.src;
    img.alt = item.alt || copy[currentLanguage].galleryDefaultCaption;
    img.loading = "lazy";

    const caption = document.createElement("figcaption");
    caption.textContent = currentLanguage === "en"
      ? (item.captionEn || item.captionKo || copy.en.galleryDefaultCaption)
      : (item.captionKo || item.captionEn || copy.ko.galleryDefaultCaption);

    figure.append(img, caption);
    gallery.append(figure);
  });
}

